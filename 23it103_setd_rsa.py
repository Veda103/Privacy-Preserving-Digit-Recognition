"""8. Membership-inference check"""

def mean_confidence(model, loader):
    model.eval()
    confidences = []

    with torch.no_grad():
        for images, labels in loader:
            outputs = model(images)
            probabilities = torch.softmax(outputs, dim=1)
            max_confidence = probabilities.max(dim=1)[0]
            confidences.extend(max_confidence.tolist())
    return np.mean(confidences)

train_eval_loader = DataLoader(
    subset,
    batch_size=BATCH_SIZE,
    shuffle=False
)

def membership_check(model, model_name):
    train_conf = mean_confidence(model, train_eval_loader)
    test_conf = mean_confidence(model, test_loader)
    gap = abs(train_conf - test_conf)

    return {
        "MODEL": model_name,
        "TRAIN": train_conf,
        "TEST": test_conf,
        "GAP": gap
    }


