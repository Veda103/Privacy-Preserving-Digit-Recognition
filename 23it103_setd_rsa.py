"""6. Train DP models for epsilon = 1, 5 and 10"""

target_epsilons = [10, 5, 1]

dp_results = []

for target_eps in target_epsilons:

    model = CNN().to(DEVICE)

    optimizer = optim.Adam(model.parameters(), lr=0.001)

    privacy_engine = PrivacyEngine()

    model, optimizer, private_loader = (
        privacy_engine.make_private_with_epsilon(
            module=model,
            optimizer=optimizer,
            data_loader=train_loader,
            target_epsilon=target_eps,
            target_delta=DELTA,
            epochs=EPOCHS,
            max_grad_norm=MAX_GRAD_NORM
        )
    )

    for epoch in range(EPOCHS):
        train_model(model, private_loader, optimizer)

    accuracy = test_accuracy(model)

    spent_epsilon = privacy_engine.get_epsilon(DELTA)

    dp_results.append({
        "TARGET_EPS": target_eps,
        "DELTA": DELTA,
        "CLIP(C)": MAX_GRAD_NORM,
        "EPOCHS": EPOCHS,
        "TEST_ACC": accuracy,
        "EPS_SPENT": spent_epsilon
    })

    print(
        f"Target ε = {target_eps} | "
        f"Accuracy = {accuracy:.2f}% | "
        f"Spent ε = {spent_epsilon:.2f}"
    )

